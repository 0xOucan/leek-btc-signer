#!/usr/bin/env python3
"""
Generate sim/vectors/seedsigner_psbt.h: every PSBT SeedSigner's own test
suite (tests/test_psbt_parser.py) hands to its PSBTParser, with the seed,
the network, and SeedSigner's verdict - the exception it raised, or what the
parse established and the signed PSBT its signing step produces.

    python gen_psbt_vectors.py --seedsigner PATH > sim/vectors/seedsigner_psbt.h
    python gen_psbt_vectors.py --seedsigner PATH --tests tests/test_flows_psbt.py \
        --array VEC_PSBT_FLOWS > sim/vectors/seedsigner_psbt_flows.h

The second records the PSBTs SeedSigner's PSBT flow tests parse, for the
flow tests in sim/test_psbt_flows.c.

Runs pytest with psbt_capture.py loaded; needs the same environment as
gen_seedsigner_vectors.py plus pytest (see README.md).
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile

NETS = {"M": "BTC_NET_MAIN", "T": "BTC_NET_TEST", "R": "BTC_NET_REGTEST"}


def c_str(s):
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def path_str(path):
    H = 0x80000000
    return "/".join("%dh" % (p - H) if p >= H else str(p) for p in path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seedsigner", required=True)
    ap.add_argument("--tests", default="tests/test_psbt_parser.py")
    ap.add_argument("--array", default="VEC_PSBT")
    args = ap.parse_args()
    ss = os.path.abspath(args.seedsigner)
    here = os.path.dirname(os.path.abspath(__file__))

    with tempfile.TemporaryDirectory() as tmp:
        cap = os.path.join(tmp, "capture.jsonl")
        env = dict(os.environ, LBS_PSBT_CAPTURE=cap,
                   PYTHONPATH=os.pathsep.join([here, os.path.join(ss, "src")]))
        # Two SeedSigner tests count key derivations and see the extra ones
        # the plugin's signing step makes; their parses are still recorded.
        subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "psbt_capture",
                        "-p", "no:cacheprovider", args.tests],
                       cwd=ss, env=env, stdout=subprocess.DEVNULL)
        records = [json.loads(l) for l in open(cap)]

    try:
        commit = subprocess.run(["git", "-C", ss, "rev-parse", "HEAD"], capture_output=True,
                                text=True).stdout.strip() or "unknown"
    except OSError:
        commit = "unknown"

    seen, unique = set(), []
    for r in records:
        key = (r["psbt"], r["mnemonic"], r["passphrase"], r["network"])
        if key not in seen:
            seen.add(key)
            unique.append(r)

    out = []
    w = out.append
    w("/*")
    w(" * GENERATED by scripts/vectors/gen_psbt_vectors.py - do not edit.")
    w(" * Every PSBT parsed by SeedSigner's %s at commit" % args.tests)
    w(" * %s, with SeedSigner's verdict. %d unique cases." % (commit, len(unique)))
    w(" * SeedSigner is MIT licensed, Copyright (c) 2021 SeedSigner.")
    w(" */")
    w("#pragma once")
    w("#include <stdbool.h>")
    w("#include <stdint.h>")
    w('#include "btc.h"')
    w("")
    w("#ifndef VEC_PSBT_TYPES")
    w("#define VEC_PSBT_TYPES")
    w("typedef struct { uint32_t output_index; const char *address; uint64_t amount; const char *path; } vec_psbt_change_t;")
    w("typedef struct { const char *address; uint64_t amount; } vec_psbt_dest_t;")
    w("typedef struct {")
    w("    const char *test, *psbt, *mnemonic, *passphrase;")
    w("    btc_net_t net;")
    w("    const char *error;              /* SeedSigner's exception class, or NULL */")
    w("    const char *policy;             /* NULL: unrecognised script */")
    w("    int m, n;                       /* -1 for single-sig */")
    w("    bool has_cosigners;")
    w("    unsigned num_inputs;")
    w("    uint64_t input_amount, spend_amount, change_amount;")
    w("    int64_t fee;")
    w("    const vec_psbt_change_t *change; unsigned n_change;")
    w("    const vec_psbt_dest_t *dest; unsigned n_dest;")
    w("    const char *op_return_hex;")
    w("    bool is_high_fee;")
    w("    const char *signed_psbt;        /* SeedSigner's trimmed signed PSBT */")
    w("    int sigs_added;")
    w("} vec_psbt_t;")
    w("#endif")
    w("")

    for i, r in enumerate(unique):
        res = r.get("result")
        if not res:
            continue
        if res["change"]:
            w("static const vec_psbt_change_t %s_CHANGE_%d[] = {" % (args.array, i))
            for c in res["change"]:
                w("    { %d, %s, %dULL, %s }," % (c["output_index"], c_str(c["address"]), c["amount"],
                                                c_str(path_str(c["path"]))))
            w("};")
        if res["destinations"]:
            w("static const vec_psbt_dest_t %s_DEST_%d[] = {" % (args.array, i))
            for a, v in res["destinations"]:
                w("    { %s, %dULL }," % (c_str(a), v))
            w("};")

    w("static const vec_psbt_t %s[] = {" % args.array)
    for i, r in enumerate(unique):
        res = r.get("result")
        fields = [c_str(r["test"].split("::", 1)[-1]), c_str(r["psbt"]), c_str(r["mnemonic"]),
                  c_str(r["passphrase"]), NETS[r["network"]], c_str(r.get("error"))]
        if res:
            fields += [c_str(res["policy_type"]),
                       str(res["m"] if res["m"] is not None else -1),
                       str(res["n"] if res["n"] is not None else -1),
                       "true" if res["has_cosigners"] else "false",
                       str(res["num_inputs"]),
                       "%dULL" % res["input_amount"], "%dULL" % res["spend_amount"],
                       "%dULL" % res["change_amount"], "%dLL" % res["fee_amount"],
                       ("%s_CHANGE_%d" % (args.array, i)) if res["change"] else "NULL", str(len(res["change"])),
                       ("%s_DEST_%d" % (args.array, i)) if res["destinations"] else "NULL",
                       str(len(res["destinations"])),
                       c_str(res["op_return"]), "true" if res["is_high_fee"] else "false",
                       c_str(r.get("signed")),
                       str(r.get("sigs_after", 0) - r.get("sigs_before", 0))]
        else:
            fields += ["NULL", "-1", "-1", "false", "0", "0", "0", "0", "0", "NULL", "0", "NULL", "0",
                       "NULL", "false", "NULL", "0"]
        w("    { %s }," % ", ".join(fields))
    w("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
