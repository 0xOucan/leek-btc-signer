#!/usr/bin/env python3
"""
Generate sim/vectors/seedsigner_tools.h: what SeedSigner's own Tools Views
compute for a new seed from dice rolls and for the final-word calculator,
captured by running them through its FlowTest harness
(tools_flows_capture.py).

    python gen_tools_vectors.py --seedsigner PATH > sim/vectors/seedsigner_tools.h

Needs the same environment as gen_psbt_vectors.py (see README.md).
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile


def c_str(s):
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seedsigner", required=True)
    args = ap.parse_args()
    ss = os.path.abspath(args.seedsigner)
    here = os.path.dirname(os.path.abspath(__file__))

    with tempfile.TemporaryDirectory() as tmp:
        cap = os.path.join(tmp, "capture.jsonl")
        env = dict(os.environ, LBS_TOOLS_CAPTURE=cap,
                   PYTHONPATH=os.pathsep.join([os.path.join(ss, "tests"), os.path.join(ss, "src")]))
        r = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
                            "--rootdir", ss, "-c", os.path.join(ss, "pytest.ini") if os.path.exists(os.path.join(ss, "pytest.ini")) else os.devnull,
                            os.path.join(here, "tools_flows_capture.py")],
                           cwd=ss, env=env, capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit(r.stdout + r.stderr)
        records = [json.loads(l) for l in open(cap)]

    commit = subprocess.run(["git", "-C", ss, "rev-parse", "HEAD"], capture_output=True,
                            text=True).stdout.strip() or "unknown"
    dice = [r for r in records if r["kind"] == "dice"]
    final = [r for r in records if r["kind"] == "final_word"]
    explorer = [r for r in records if r["kind"] == "explorer"]

    out = []
    w = out.append
    w("/*")
    w(" * GENERATED by scripts/vectors/gen_tools_vectors.py - do not edit.")
    w(" * SeedSigner's own Tools Views at commit %s, run through its" % commit)
    w(" * FlowTest harness: %d dice cases, %d final-word cases, %d address lists." % (len(dice), len(final), len(explorer)))
    w(" * SeedSigner is MIT licensed, Copyright (c) 2021 SeedSigner.")
    w(" */")
    w("#pragma once")
    w("#include <stdbool.h>")
    w('#include "btc.h"')
    w("")
    w("typedef struct { const char *rolls, *mnemonic, *fingerprint; } vec_tools_dice_t;")
    w("typedef struct {")
    w("    int n;                          /* 12 or 24 */")
    w("    const char *mode;               /* \"coins\", \"word\" or \"zeros\" */")
    w("    const char *words;              /* the first n-1 words typed */")
    w("    const char *flips, *chosen;     /* the coin flips, or the word chosen */")
    w("    /* ToolsCalcFinalWordShowFinalWordView's figures */")
    w("    const char *selected_final_word, *selected_final_bits, *checksum_bits, *actual_final_word;")
    w("    const char *mnemonic, *fingerprint;")
    w("} vec_tools_final_t;")
    w("typedef struct {")
    w("    const char *mnemonic;")
    w("    btc_net_t net;")
    w("    const char *script_type;        /* SeedSigner's: \"nat\" \"nes\" \"leg\" \"tr\" */")
    w("    bool is_change;")
    w("    const char *derivation_path, *fingerprint;")
    w("    const char *addresses[20];      /* the first two pages, indexes 0 to 19 */")
    w("} vec_tools_explorer_t;")
    w("")
    w("static const vec_tools_dice_t VEC_TOOLS_DICE[] = {")
    for r in dice:
        w("    { %s, %s, %s }," % (c_str(r["rolls"]), c_str(r["mnemonic"]), c_str(r["fingerprint"])))
    w("};")
    w("static const vec_tools_final_t VEC_TOOLS_FINAL[] = {")
    for r in final:
        w("    { %d, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s }," % (
            r["n"], c_str(r["mode"]), c_str(r["words"]), c_str(r["flips"]), c_str(r["chosen"]),
            c_str(r["selected_final_word"]), c_str(r["selected_final_bits"]), c_str(r["checksum_bits"]),
            c_str(r["actual_final_word"]), c_str(r["mnemonic"]), c_str(r["fingerprint"])))
    w("};")
    nets = {"M": "BTC_NET_MAIN", "T": "BTC_NET_TEST", "R": "BTC_NET_REGTEST"}
    w("static const vec_tools_explorer_t VEC_TOOLS_EXPLORER[] = {")
    for r in explorer:
        assert len(r["addresses"]) == 20, len(r["addresses"])
        w("    { %s, %s, %s, %s, %s, %s, {" % (c_str(r["mnemonic"]), nets[r["network"]], c_str(r["script_type"]),
                                            "true" if r["is_change"] else "false",
                                            c_str(r["derivation_path"]), c_str(r["fingerprint"])))
        for a in r["addresses"]:
            w("        %s," % c_str(a))
        w("    } },")
    w("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
