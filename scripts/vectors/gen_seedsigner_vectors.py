#!/usr/bin/env python3
"""
Generate sim/vectors/seedsigner_core.h: seed, key, address, SeedQR, dice and
BIP-85 vectors, by running SeedSigner's own code (see README.md).

Two sources, both kept:
  * the vector tables in SeedSigner's tests (which come from the BIPs), read
    by running each test function's prelude, so nothing is hand-copied;
  * SeedSigner's helpers run over a wider grid (every script type and
    network, change and receive, null-byte entropy), so the port is checked
    against SeedSigner's behaviour, not only against the BIPs.
"""
import argparse
import ast
import hashlib
import os
import random
import subprocess
import sys


def c_str(s):
    if s is None:
        return "NULL"
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


NETS = {"M": "BTC_NET_MAIN", "T": "BTC_NET_TEST", "R": "BTC_NET_REGTEST"}
EMBIT_NETS = {"main": "BTC_NET_MAIN", "test": "BTC_NET_TEST", "regtest": "BTC_NET_REGTEST"}
SIGS = {"ss": "BTC_SIG_SINGLE", "ms": "BTC_SIG_MULTI"}
SCRIPTS = {"leg": "BTC_SCRIPT_P2PKH", "nes": "BTC_SCRIPT_P2SH_P2WPKH",
           "nat": "BTC_SCRIPT_P2WPKH", "tr": "BTC_SCRIPT_P2TR"}


def test_prelude_locals(path, func_name, stop_at="func"):
    """Run a test function's statements up to `func = ...` and return its
    locals: the vector tables, built exactly as the test builds them."""
    # The tests import pytest only for raises(); the prelude never uses it.
    sys.modules.setdefault("pytest", type(sys)("pytest"))
    tree = ast.parse(open(path).read())
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == func_name)
    mod_globals = {}
    exec(compile(ast.Module(body=[n for n in tree.body if isinstance(n, (ast.Import, ast.ImportFrom))],
                            type_ignores=[]), path, "exec"), mod_globals)
    local = dict(mod_globals)
    for stmt in fn.body:
        if (isinstance(stmt, ast.Assign) and len(stmt.targets) == 1
                and isinstance(stmt.targets[0], ast.Name) and stmt.targets[0].id == stop_at):
            break
        if isinstance(stmt, (ast.For, ast.While, ast.With, ast.If)):
            break       # the prelude is over; this is the test itself
        if isinstance(stmt, (ast.Assign, ast.Import, ast.ImportFrom)):
            exec(compile(ast.Module(body=[stmt], type_ignores=[]), path, "exec"), local)
    return local


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seedsigner", required=True, help="SeedSigner checkout")
    args = ap.parse_args()
    ss = os.path.abspath(args.seedsigner)
    sys.path.insert(0, os.path.join(ss, "src"))
    tests = os.path.join(ss, "tests")

    from embit import bip32, bip39
    from embit.networks import NETWORKS
    from seedsigner.helpers import embit_utils, mnemonic_generation
    from seedsigner.models.encode_qr import CompactSeedQrEncoder, SeedQrEncoder, StaticXpubQrEncoder
    from seedsigner.models.seed import Seed
    from seedsigner.models.settings_definition import SettingsConstants as SC

    try:
        commit = subprocess.run(["git", "-C", ss, "rev-parse", "HEAD"], capture_output=True,
                                text=True).stdout.strip() or "unknown"
    except OSError:
        commit = "unknown"

    out = []
    w = out.append
    w("/*")
    w(" * GENERATED by scripts/vectors/gen_seedsigner_vectors.py - do not edit.")
    from importlib.metadata import version
    w(" * From SeedSigner commit %s, embit %s." % (commit, version("embit")))
    w(" * SeedSigner is MIT licensed, Copyright (c) 2021 SeedSigner.")
    w(" */")
    w("#pragma once")
    w("#include <stdbool.h>")
    w('#include "btc.h"')
    w("")

    # ---- Standard derivation paths (test_get_standard_derivation_path) ----
    loc = test_prelude_locals(os.path.join(tests, "test_embit_utils.py"), "test_get_standard_derivation_path")
    w("typedef struct { btc_net_t net; btc_sig_t sig; btc_script_t script; const char *path; } vec_path_t;")
    w("static const vec_path_t VEC_PATHS[] = {")
    n = 0
    for a, expected in loc["vectors_args_expected"].items():
        if len(a) != 3 or a[0] not in NETS:
            continue    # the nonsense-argument cases have no C equivalent
        sig = SIGS.get(a[1], "BTC_SIG_INVALID")
        scr = SCRIPTS.get(a[2], "BTC_SCRIPT_INVALID")
        path = expected if isinstance(expected, str) else None
        w("    { %s, %s, %s, %s }," % (NETS[a[0]], sig, scr, c_str(path)))
        n += 1
    w("};")
    w("")

    # ---- xpub at a path (test_get_xpub) ----
    loc = test_prelude_locals(os.path.join(tests, "test_embit_utils.py"), "test_get_xpub")
    w("/* BIP-32/49/84/86 and SLIP-132 vectors, generic xpub/tpub version. */")
    w("typedef struct { const char *seed_hex; const char *path; btc_net_t net; const char *xpub; } vec_xpub_t;")
    w("static const vec_xpub_t VEC_XPUB[] = {")
    for (seed, path, net), expected in loc["vectors_args_expected"].items():
        w("    { %s, %s, %s, %s }," % (c_str(seed.hex()), c_str(path), EMBIT_NETS[net], c_str(expected)))
    w("};")
    w("")

    # ---- Single-sig addresses (test_get_single_sig_address) + grid ----
    loc = test_prelude_locals(os.path.join(tests, "test_embit_utils.py"), "test_get_single_sig_address")
    w("typedef struct { const char *xpub; btc_script_t script; unsigned index; bool change;")
    w("                 btc_net_t net; const char *address; } vec_addr_t;")
    w("static const vec_addr_t VEC_ADDR[] = {")
    for (key, script, index, change, net), expected in loc["vectors_args_expected"].items():
        if script not in SCRIPTS:
            continue
        w("    { %s, %s, %u, %s, %s, %s }," % (c_str(key.to_string()), SCRIPTS[script], index,
                                             "true" if change else "false", EMBIT_NETS[net], c_str(expected)))
    # The grid: SeedSigner's helper over every script, network, branch.
    grid_mnemonic = ("abandon " * 11 + "about").split()
    grid_seed = Seed(grid_mnemonic)
    for net in ["M", "T", "R"]:
        embit_net = SC.map_network_to_embit(net)
        for script in ["leg", "nes", "nat", "tr"]:
            path = embit_utils.get_standard_derivation_path(net, SC.SINGLE_SIG, script)
            xpub = embit_utils.get_xpub(grid_seed.seed_bytes, path, embit_net)
            for change in (False, True):
                for index in (0, 1, 7, 1000):
                    addr = embit_utils.get_single_sig_address(xpub, script, index, change, embit_net)
                    w("    { %s, %s, %u, %s, %s, %s }," % (c_str(xpub.to_string()), SCRIPTS[script], index,
                                                         "true" if change else "false", NETS[net], c_str(addr)))
    w("};")
    w("")

    # ---- Seeds: fingerprint and the xpub export SeedSigner shows ----
    w("/* A seed, its fingerprint, and the static xpub export of SeedSigner's")
    w(" * StaticXpubQrEncoder: [fingerprint/path]xpub with the SLIP-132 version")
    w(" * SeedSigner's detect_version picks. */")
    w("typedef struct { const char *mnemonic; const char *passphrase; const char *fingerprint;")
    w("                 btc_net_t net; btc_sig_t sig; btc_script_t script; const char *path;")
    w("                 const char *xpub_export; } vec_export_t;")
    w("static const vec_export_t VEC_EXPORT[] = {")
    export_seeds = [
        ("abandon " * 11 + "about", ""),
        ("abandon " * 11 + "about", "TREZOR"),
        ("resource timber firm banner horror pupil frozen main pear direct pioneer broken grid "
         "core insane begin sister pony end debate task silk empty curious", ""),
        ("crew marble private differ race truly blush basket crater affair prepare unique",
         "correct horse battery staple"),
    ]
    for mnemonic, passphrase in export_seeds:
        seed = Seed(mnemonic.split(), passphrase=passphrase)
        fp = seed.get_fingerprint()
        for net in ["M", "T"]:
            for sig, scripts in (("ss", ["leg", "nes", "nat", "tr"]), ("ms", ["nes", "nat"])):
                for script in scripts:
                    path = embit_utils.get_standard_derivation_path(net, sig, script)
                    enc = StaticXpubQrEncoder(seed=seed, derivation=path, network=net, sig_type=sig)
                    w("    { %s, %s, %s, %s, %s, %s, %s, %s }," % (
                        c_str(mnemonic), c_str(passphrase), c_str(fp), NETS[net], SIGS[sig],
                        SCRIPTS[script], c_str(path), c_str(enc.next_part())))
    w("};")
    w("")

    # ---- SeedQR, standard and compact (test_seedqr.py, deterministic) ----
    rng = random.Random(0x5EED)
    rb = lambda k: bytes(rng.getrandbits(8) for _ in range(k))
    entropies = [b"\x00" * 16, b"\xff" * 16, b"\x00" * 32, b"\xff" * 32]
    loc = test_prelude_locals(os.path.join(tests, "test_seedqr.py"),
                              "test_compact_seedqr_bytes_interpretable_as_str", stop_at="__never__")
    entropies += [e for e in loc.get("entropy_bytes_tests", []) if len(e) in (16, 32)]
    # The null-byte placements of test_compact_seedqr_handles_null_bytes,
    # with seeded bytes in place of os.urandom.
    entropies += [b"\x00" + rb(31), rb(10) + b"\x00" + rb(21), rb(31) + b"\x00",
                  rb(5) + b"\x00" + rb(5) + b"\x00" + rb(20), rb(10) + b"\x00\x00" + rb(20),
                  b"\x00" + rb(15), rb(5) + b"\x00" + rb(10), rb(15) + b"\x00",
                  rb(5) + b"\x00" + rb(5) + b"\x00" + rb(4), rb(10) + b"\x00\x00" + rb(4)]
    entropies += [rb(16) for _ in range(6)] + [rb(32) for _ in range(6)]
    w("typedef struct { const char *entropy_hex; const char *mnemonic; const char *seedqr;")
    w("                 const char *compact_hex; } vec_seedqr_t;")
    w("static const vec_seedqr_t VEC_SEEDQR[] = {")
    for e in entropies:
        mnemonic = bip39.mnemonic_from_bytes(e).split()
        std = SeedQrEncoder(mnemonic=mnemonic).next_part()
        compact = CompactSeedQrEncoder(mnemonic=mnemonic).next_part()
        w("    { %s, %s, %s, %s }," % (c_str(e.hex()), c_str(" ".join(mnemonic)), c_str(std),
                                      c_str(bytes(compact).hex())))
    w("};")
    w("")

    # ---- Dice, final word, coin flips (test_mnemonic_generation.py) ----
    rolls = ["123456",                                  # Coldcard's published sample
             "522222222222222222222222222222222222222222222555555555555555555555555555555555555555555555555555555",
             "222222222222222222222222222222222222222222222555555555555555555555555555555555555555555555555555555",
             "222222222222222222222222222222222222222222222555555555555555555555555555555555555555555555555555556",
             "12345612345612345612345612345612345612345612345612",
             "1" * 50, "6" * 50]
    rolls += ["".join(str(rng.randint(1, 6)) for _ in range(n)) for n in (50, 50, 99, 99, 99)]
    w("typedef struct { const char *rolls; const char *mnemonic; } vec_dice_t;")
    w("static const vec_dice_t VEC_DICE[] = {")
    for r in rolls:
        w("    { %s, %s }," % (c_str(r), c_str(" ".join(mnemonic_generation.generate_mnemonic_from_dice(r)))))
    w("};")
    w("")

    partials = ["crawl focus rescue cable view pledge rather dinner cousin unfair day",
                "bubble father debate ankle injury fence mesh evolve section wet coyote violin pyramid "
                "flower rent arrow round clutch myth safe base skin mobile",
                "crawl focus rescue cable view pledge rather dinner cousin unfair day abandon"]
    wl = bip39.WORDLIST
    partials += [" ".join(rng.choice(wl) for _ in range(n)) for n in (11, 11, 12, 23, 23, 24)]
    errors = ["abandon " * 9 + "about", "abandon " * 21 + "about",
              "devote myth base logic dust horse nut collect buddy element eyebrow visit empty dress jungle",
              "foobar " * 11 + "about"]
    w("/* mnemonic NULL: SeedSigner raises. */")
    w("typedef struct { const char *partial; const char *mnemonic; } vec_checksum_t;")
    w("static const vec_checksum_t VEC_CHECKSUM[] = {")
    for p in partials:
        w("    { %s, %s }," % (c_str(p), c_str(" ".join(mnemonic_generation.calculate_checksum(p)))))
    for p in errors:
        try:
            mnemonic_generation.calculate_checksum(p.strip())
            raise SystemExit("expected an error for %r" % p)
        except SystemExit:
            raise
        except Exception:
            w("    { %s, NULL }," % c_str(p.strip()))
    w("};")
    w("")

    flips = ["".join(rng.choice("01") for _ in range(n)) for n in (128, 128, 256, 256)]
    w("typedef struct { const char *flips; const char *mnemonic; } vec_flips_t;")
    w("static const vec_flips_t VEC_FLIPS[] = {")
    for f in flips:
        w("    { %s, %s }," % (c_str(f), c_str(" ".join(mnemonic_generation.generate_mnemonic_from_coin_flips(f)))))
    w("};")
    w("")
    partial_flips = ["0101010", "1111111", "0000000", "010", "111", "000"]
    w("typedef struct { const char *flips; const char *word; } vec_partial_word_t;")
    w("static const vec_partial_word_t VEC_PARTIAL_WORD[] = {")
    for f in partial_flips:
        w("    { %s, %s }," % (c_str(f), c_str(mnemonic_generation.get_partial_final_word(f))))
    w("};")
    w("")

    # ---- BIP-85 (test_bip85.py + more indexes) ----
    w("typedef struct { const char *mnemonic; unsigned index; unsigned words; const char *child; } vec_bip85_t;")
    w("static const vec_bip85_t VEC_BIP85[] = {")
    for mnemonic, _ in export_seeds[:3]:
        seed = Seed(mnemonic.split())
        for index in (0, 1, 7):
            for words in (12, 24):
                w("    { %s, %u, %u, %s }," % (c_str(mnemonic), index, words,
                                              c_str(seed.get_bip85_child_mnemonic(index, words))))
    w("};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
